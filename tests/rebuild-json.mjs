import { createRequire } from 'node:module';
const { chromium } = createRequire(import.meta.url)('playwright');
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 1500, height: 950 } });
const logs = [];
p.on('pageerror', (e) => logs.push('PAGEERROR: ' + e.message));
await p.goto('http://localhost:8765/index.html'); await p.waitForTimeout(800);
await p.click('text=Rangos: alcance de los sentidos'); await p.waitForTimeout(1500);
await p.click('.tabs >> text=Datos').catch(async () => { await p.click('text=Datos >> nth=0'); });
await p.waitForTimeout(400);
await p.click('text=+ Agregar datos'); await p.waitForTimeout(400);
const [fc] = await Promise.all([p.waitForEvent('filechooser'), p.click('#app-dialog >> text=Elegir archivo…')]);
await fc.setFiles('tests/img/sentidos.json'); await p.waitForTimeout(700);
await p.screenshot({ path: '/tmp/claude-0/js1.png' });
await p.click('#app-dialog >> text=Rehacer el gráfico completo'); await p.waitForSelector('.itp-grid', { timeout: 20000 }); await p.waitForTimeout(400);
await p.screenshot({ path: '/tmp/claude-0/js2.png' });
await p.click('#app-dialog >> text=Crear la figura'); await p.waitForTimeout(2000);
await p.screenshot({ path: '/tmp/claude-0/js3.png' });
logs.push(JSON.stringify(await p.evaluate(() => { const f = window.__et.current.fig; return { n: window.__et.current.figures.length, panel: f.panels[0].type, o: f.panels[0].options }; })));
console.log(logs.join('\n')); await b.close();
